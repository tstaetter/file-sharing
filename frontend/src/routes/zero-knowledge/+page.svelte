						3
					</div>
					<div>
						<h3 class="text-sm font-semibold text-slate-700">Direct upload to storage</h3>
						<p class="mt-1">
							Each encrypted chunk is uploaded directly to Cloudflare R2 via presigned URLs
							generated by our backend. Critically, the file data <strong>never passes through
							our backend servers</strong> — it travels straight from your browser to R2. The
							backend only coordinates the multipart upload flow. It sees upload IDs and part
							numbers, but never the actual bytes, plaintext or ciphertext.
						</p>
					</div>
				</div>

				<!-- Step 4 -->
				<div class="flex gap-4 mt-5">
					<div
						class="shrink-0 w-8 h-8 rounded-full bg-violet-100 text-violet-600 flex items-center justify-center text-sm font-bold"
					>
						4
					</div>
					<div>
						<h3 class="text-sm font-semibold text-slate-700">
							Key embedded in the URL hash fragment
						</h3>
						<p class="mt-1">
							The encryption key is encoded as URL-safe base64 and appended to the
							shareable link after a <code class="bg-slate-100 px-1 py-0.5 rounded text-xs">#</code>
							(hash). For example:
							<code class="bg-slate-100 px-1 py-0.5 rounded text-xs break-all">/f/uuid#base64key</code>.
							Hash fragments are <strong>never transmitted in HTTP requests</strong> — this is a
							fundamental browser security property. When someone opens the link, the key is
							extracted locally by JavaScript in their browser. The server never sees it.
						</p>
					</div>
				</div>

				<!-- Step 5 -->
				<div class="flex gap-4 mt-5">
					<div
