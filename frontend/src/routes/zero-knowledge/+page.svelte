			<section>
				<h2 class="text-base font-semibold text-slate-800 mb-2">Why the Hash Fragment Matters</h2>
				<p>
					The URL hash fragment (the part after <code class="bg-slate-100 px-1 py-0.5 rounded text-xs">#</code>)
					is special in HTTP: browsers <strong>never include it in HTTP requests</strong>. This is
					not something we enforce — it's a fundamental rule of how the web works. When you type a
					URL with a hash into your browser, or when someone clicks a link with a hash, the
					fragment stays in the browser's address bar and is accessible to JavaScript, but it is
					never sent over the network in any HTTP request.
				</p>
				<p class="mt-2">
					This means the encryption key — which we embed in the hash fragment — is physically
					impossible for our servers to receive, even if we wanted to. The key exchange happens
					entirely between the sender and the recipient, mediated only by the URL they share
					through any channel they choose (messenger, email, QR code, etc.).
				</p>
				<div class="mt-3 p-3 bg-slate-50 border border-slate-200 rounded-lg">
					<p class="text-xs text-slate-600">
						<strong>Example capability URL:</strong><br />
						<code class="text-xs break-all">https://filez.zone/f/a1b2c3d4-e5f6-7890-abcd-ef1234567890#dGhpcyBpcyBhIGtleQ</code>
					</p>
					<p class="text-xs text-slate-500 mt-1.5">
						The browser sends <code class="bg-slate-100 px-1 py-0.5 rounded text-xs">GET /f/a1b2c3d4-...</code>
						to the server. The part after <code class="bg-slate-100 px-1 py-0.5 rounded text-xs">#</code> is
						never transmitted. JavaScript extracts it locally to decrypt the file.
					</p>
				</div>
			</section>

			<section>
				<h2 class="text-base font-semibold text-slate-800 mb-2">End-to-End vs. Zero Knowledge</h2>
				<p>
					These terms are related but distinct:
				</p>
				<ul class="list-disc pl-5 mt-2 space-y-2">
					<li>
						<strong>End-to-end encryption (E2EE)</strong> means data is encrypted on the
						sender's device and can only be decrypted on the recipient's device. No
						intermediary can read it in transit. filez.zone implements this: only the
						sender and recipient ever hold the key.
					</li>
					<li>
						<strong>Zero knowledge</strong> goes a step further: it means the service
						provider has no technical ability to access the plaintext, even if compelled.
						This is achieved because we never possess the key at any point — it's generated
						locally, transmitted only through the hash fragment, and used only in the
						browser.
					</li>
				</ul>
				<p class="mt-2">
					filez.zone is both end-to-end encrypted <em>and</em> zero-knowledge. We cannot
					decrypt your files even if we wanted to or were legally required to.
				</p>
			</section>

