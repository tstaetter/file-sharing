					<div>
						<h3 class="text-sm font-semibold text-slate-700">Key generation in your browser</h3>
						<p class="mt-1">
							When you pick a file to share, a unique 256-bit AES-GCM key is generated
							directly in your browser using the
							<a
								href="https://developer.mozilla.org/en-US/docs/Web/API/Web_Crypto_API"
								class="text-blue-500 hover:text-blue-600 underline"
