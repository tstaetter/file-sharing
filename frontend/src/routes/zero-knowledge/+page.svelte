						<h3 class="text-sm font-semibold text-slate-700">
							Download, decrypt, and burn after reading
						</h3>
						<p class="mt-1">
							When a recipient opens the link, their browser requests the encrypted blob
							from our backend. The backend fetches it from R2, streams it back, and
							<strong>immediately deletes the object from storage</strong>. The recipient's
							browser then decrypts each chunk using the key from the hash fragment and
							reassembles the original file. After this single download, the file no longer
							exists on our infrastructure — burn after reading.
						</p>
					</div>
				</div>
