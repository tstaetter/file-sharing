			<section>
				<h2 class="text-base font-semibold text-slate-800 mb-2">What is Zero Knowledge?</h2>
				<p>
					<strong>Zero knowledge</strong> means that the service provider — filez.zone — has
					<strong>zero knowledge</strong> of your file contents. We designed our entire system so
					that the server never sees the plaintext data you upload, never possesses the encryption
					keys, and never has the ability to decrypt your files. Even if our servers were
					compromised, your data remains unreadable.
				</p>
				<p class="mt-2">
					This is not a marketing claim — it's enforced by cryptography and architecture. The
					encryption key is generated in your browser, used only in your browser, and embedded in
					a shareable link in a way that browsers never transmit to web servers. We simply store
					and serve opaque encrypted blobs we cannot read.
				</p>
			</section>

			<section>
				<h2 class="text-base font-semibold text-slate-800 mb-2">How It Works</h2>

				<!-- Step 1 -->
				<div class="flex gap-4 mt-4">
					<div
