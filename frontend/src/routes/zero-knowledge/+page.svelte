			<section>
				<h2 class="text-base font-semibold text-slate-800 mb-2">Limitations &amp; Responsibilities</h2>
				<p>
					Zero knowledge protects your data from us, but it cannot protect against everything.
					You are responsible for:
				</p>
				<ul class="list-disc pl-5 mt-2 space-y-1.5">
					<li>
						<strong>Sharing the link securely.</strong> Anyone with the capability URL can
						download the file once. If you share it over an insecure channel and it's
						intercepted, the interceptor can access the file before the intended
						recipient.
					</li>
					<li>
						<strong>Verifying the recipient.</strong> The burn-after-read model means the
						first person to open the link gets the file. Make sure you're sharing with the
						right person.
					</li>
					<li>
						<strong>Your own device security.</strong> The encryption key is generated and
						used in your browser. If your device is compromised (malware, keyloggers,
						browser extensions), the key could be intercepted before it's embedded in the
						hash fragment.
					</li>
				</ul>
				<p class="mt-2">
					These are inherent trade-offs in any zero-knowledge system where the service
					provider is intentionally kept out of the trust boundary. We believe this is the
					right trade-off: you control the data, and with that comes the responsibility to
					handle the link with care.
				</p>
