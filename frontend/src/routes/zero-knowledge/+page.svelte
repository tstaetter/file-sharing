					</div>
					<div>
						<h3 class="text-sm font-semibold text-slate-700">Client-side encryption</h3>
						<p class="mt-1">
							The file is split into 5 MB chunks. Each chunk is encrypted with AES-256-GCM
							using a random 12-byte initialization vector (IV) per chunk. The output for
							each chunk is: <code class="bg-slate-100 px-1 py-0.5 rounded text-xs">IV (12 bytes) || ciphertext || GCM tag (16 bytes)</code>.
							All encryption happens locally — the original file never leaves your browser.
						</p>
					</div>
				</div>

				<!-- Step 3 -->
				<div class="flex gap-4 mt-5">
					<div
						class="shrink-0 w-8 h-8 rounded-full bg-violet-100 text-violet-600 flex items-center justify-center text-sm font-bold"
